// Builds Code.gs for the Apps Script project from the tested clinic rules, the booking engine and the
// sheet adapter. Run: node "Booking Appointment using Telnyx Voice Agent/apps-script/build-apps-script.js"
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const read = (p) => fs.readFileSync(path.join(__dirname, p), 'utf8').replace(/\r\n/g, '\n');
const stripExports = (src) => src.replace(/\nmodule\.exports = \{[\s\S]*?\};\s*$/, '\n');
const stripNodeOnly = (src) => src.replace(/\/\/ @node-only-start\n[\s\S]*?\/\/ @node-only-end\n?/g, '');

const rules = stripExports(read('../engine/clinic-rules.js'));
const engine = stripNodeOnly(read('booking-engine.js'));
const adapter = read('sheet-adapter.gs.js');
for (const [name, src] of [['clinic-rules', rules], ['booking-engine', engine]]) {
  if (/module\.exports|require\(/.test(src)) throw new Error(`${name}: Node-only code left in Code.gs`);
}

// Short content hash, reported by doGet, so a live deployment can be checked against this file.
const version = crypto.createHash('sha256').update(`${rules}${engine}${adapter}`).digest('hex').slice(0, 8);

const out = `// Smile Care Dental Clinic - booking engine (Google Apps Script web app).
// GENERATED by build-apps-script.js from engine/clinic-rules.js, apps-script/booking-engine.js and
// apps-script/sheet-adapter.gs.js. Do not edit here; edit those files and rebuild.

// ==== clinic rules ====
${rules.trim()}

// ==== booking engine ====
${engine.trim()}

const ENGINE_VERSION = '${version}';

${adapter.trim()}
`;
fs.writeFileSync(path.join(__dirname, 'Code.gs'), out);
console.log(`wrote Code.gs (${out.split('\n').length} lines, version ${version})`);
